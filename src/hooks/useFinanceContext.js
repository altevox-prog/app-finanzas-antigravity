import { useMemo } from 'react';
import { useFinancialOperations } from './useFinancialOperations';

/**
 * useFinanceContext
 * Hook especializado en consolidar las operaciones financieras cruzadas y construir
 * los objetos masivos memorizados `financeData` y `financeActions`.
 */
export function useFinanceContext({
  // Estado de datos base
  accounts = [],
  setAccounts,
  transactions = [],
  setTransactions,
  categories = [],
  setCategories,
  debtsAndLoans = [],
  setDebtsAndLoans,
  investments = [],
  setInvestments,
  recurringPayments = [],
  setRecurringPayments,
  subscriptions = [],
  setSubscriptions,
  budgets = {},
  setBudgets,
  savingsGoals = [],
  setSavingsGoals,
  userProfile = {},
  setUserProfile,
  trm = 4000,
  user = null,
  theme = 'dark',
  setTheme,
  securitySettings = {},
  setSecuritySettings,
  isLocked = false,
  failedAttempts = 0,
  showTutorial = false,
  setShowTutorial,
  isResettingRef,

  // Handlers base de entidades
  baseAddTransaction,
  baseSaveTransaction,
  baseUpdateTransaction,
  baseDeleteTransaction,
  baseExecuteTransfer,
  baseAddPayment,
  baseDeletePayment,
  baseAddDisbursement,
  baseAddInvestment,
  baseSaveInvestment,
  baseUpdateInvestment,
  baseDeleteInvestment,
  baseAddDebtOrLoan,
  baseSaveLoan,
  baseDeleteDebtOrLoan,

  // Categorías y subcategorías handlers
  handleAddCategory,
  handleUpdateCategory,
  handleDeleteCategory,
  handleAddSubcategory,
  handleUpdateSubcategory,
  handleDeleteSubcategory,

  // Cuentas handlers
  handleAddAccount,
  handleUpdateAccount,
  handleDeleteAccount,
  handleReorderAccounts,

  // Deudas y recurrentes handlers
  handleUpdateDebtOrLoan,
  handleAddRecurring,
  handleUpdateRecurring,
  handleDeleteRecurring,
  handleToggleActiveRecurring,

  // Metas handlers
  handleAddGoal,
  handleUpdateGoal,
  handleDeleteGoal,

  // Perfil, reseteo y sincronización handlers
  handleUpdateProfile,
  handleRestoreBackup,
  handleResetData,
  pushLocalToCloud,
  pullCloudToLocal,
  handleGlobalLogout,
  syncStatus = 'idle',
  syncUser = null,
  isCloudEnabled = false,

  // Fechas y navegación
  selectedDate,
  setSelectedDate,
  selectedMonth,
  selectedYear,
  selectedDay,
  setSelectedDay,
  showMonthPicker,
  setShowMonthPicker,
  currentMonthLabel,
  handlePrevMonth,
  handleNextMonth,
  handleResetToToday,
  handleChangeMonth,

  // Widgets & UI
  widgets,
  setWidgets,
  isEditWidgetsModalOpen,
  setIsEditWidgetsModalOpen,
  tomorrowDebtAlerts = [],
  handleDismissAlert,
  handleReviewDebtAlert,
  formatMoney,
  fromSettings,
  setFromSettings,
  handleGoBackFromSubView,
  handleUnlock,
  handleVerifyPin,
  handleUpdatePin,

  // Métricas analíticas
  monthlyTransactions = [],
  scopedTransactions = [],
  monthlyStats = {},
  netWorth = 0,
  taxMetrics = {},

  // Navegación de pestañas & modales
  activeTab,
  handleTabChange,
  handleResetTab,
  modalControls = {}
} = {}) {
  // Orquestador central de operaciones financieras cruzadas
  const financialOps = useFinancialOperations({
    accounts,
    setAccounts,
    transactions,
    setTransactions,
    debtsAndLoans,
    setDebtsAndLoans,
    investments,
    setInvestments,
    categories,
    setCategories,
    trm,
    userProfile,
    isResettingRef,
    baseAddTransaction,
    baseSaveTransaction,
    baseUpdateTransaction,
    baseDeleteTransaction,
    baseExecuteTransfer,
    baseAddPayment,
    baseDeletePayment,
    baseAddDisbursement,
    baseAddInvestment,
    baseDeleteInvestment,
    baseAddDebtOrLoan,
    baseSaveLoan,
    baseDeleteDebtOrLoan
  });

  // 1. Objeto consolidado y memorizado de datos financieros
  const financeData = useMemo(() => ({
    accounts,
    transactions,
    monthlyTransactions,
    scopedTransactions,
    categories,
    investments,
    debtsAndLoans,
    recurringPayments,
    subscriptions,
    budgets,
    savingsGoals,
    monthlyStats,
    netWorth,
    taxMetrics,
    trm,
    userProfile,
    selectedDate,
    selectedMonth,
    selectedYear,
    selectedDay,
    currentMonthLabel,
    widgets,
    tomorrowDebtAlerts,
    user,
    theme,
    securitySettings,
    isLocked,
    failedAttempts,
    showTutorial,
    syncStatus,
    syncUser,
    isCloudEnabled
  }), [
    accounts,
    transactions,
    monthlyTransactions,
    scopedTransactions,
    categories,
    investments,
    debtsAndLoans,
    recurringPayments,
    subscriptions,
    budgets,
    savingsGoals,
    monthlyStats,
    netWorth,
    taxMetrics,
    trm,
    userProfile,
    selectedDate,
    selectedMonth,
    selectedYear,
    selectedDay,
    currentMonthLabel,
    widgets,
    tomorrowDebtAlerts,
    user,
    theme,
    securitySettings,
    isLocked,
    failedAttempts,
    showTutorial,
    syncStatus,
    syncUser,
    isCloudEnabled
  ]);

  // 2. Objeto consolidado y memorizado de acciones y operaciones
  const financeActions = useMemo(() => ({
    ...financialOps,
    ...modalControls,
    handleTabChange,
    handleResetTab,
    setSelectedDate,
    setSelectedDay,
    setWidgets,
    setBudgets,
    setSubscriptions,
    setSecuritySettings,
    setTheme,
    setShowTutorial,
    showMonthPicker,
    setShowMonthPicker,
    isEditWidgetsModalOpen,
    setIsEditWidgetsModalOpen,
    handleUnlock,
    handleVerifyPin,
    handleUpdatePin,
    handleReviewDebtAlert,
    handleDismissAlert,
    formatMoney,
    handleGoBackFromSubView,
    fromSettings,
    setFromSettings,
    handleAddCategory,
    handleUpdateCategory,
    handleDeleteCategory,
    handleAddSubcategory,
    handleUpdateSubcategory,
    handleDeleteSubcategory,
    handleAddAccount,
    handleUpdateAccount,
    handleDeleteAccount,
    handleReorderAccounts,
    handleUpdateDebtOrLoan,
    handleUpdateInvestment: baseUpdateInvestment,
    handleAddRecurring,
    handleUpdateRecurring,
    handleDeleteRecurring,
    handleToggleActiveRecurring,
    handleAddGoal,
    handleUpdateGoal,
    handleDeleteGoal,
    handlePrevMonth,
    handleNextMonth,
    handleResetToToday,
    handleChangeMonth,
    handleRestoreBackup,
    handleResetData,
    handleUpdateProfile,
    pushLocalToCloud,
    pullCloudToLocal,
    onLogout: handleGlobalLogout
  }), [
    financialOps,
    modalControls,
    handleTabChange,
    handleResetTab,
    setSelectedDate,
    setSelectedDay,
    setWidgets,
    setBudgets,
    setSubscriptions,
    setSecuritySettings,
    setTheme,
    setShowTutorial,
    showMonthPicker,
    setShowMonthPicker,
    isEditWidgetsModalOpen,
    setIsEditWidgetsModalOpen,
    handleUnlock,
    handleVerifyPin,
    handleUpdatePin,
    handleReviewDebtAlert,
    handleDismissAlert,
    formatMoney,
    handleGoBackFromSubView,
    fromSettings,
    setFromSettings,
    handleAddCategory,
    handleUpdateCategory,
    handleDeleteCategory,
    handleAddSubcategory,
    handleUpdateSubcategory,
    handleDeleteSubcategory,
    handleAddAccount,
    handleUpdateAccount,
    handleDeleteAccount,
    handleReorderAccounts,
    handleUpdateDebtOrLoan,
    baseUpdateInvestment,
    handleAddRecurring,
    handleUpdateRecurring,
    handleDeleteRecurring,
    handleToggleActiveRecurring,
    handleAddGoal,
    handleUpdateGoal,
    handleDeleteGoal,
    handlePrevMonth,
    handleNextMonth,
    handleResetToToday,
    handleChangeMonth,
    handleRestoreBackup,
    handleResetData,
    handleUpdateProfile,
    pushLocalToCloud,
    pullCloudToLocal,
    handleGlobalLogout
  ]);

  return {
    financeData,
    financeActions,
    financialOps
  };
}

export default useFinanceContext;
