import { useMemo } from 'react';
import { useFinancialOperations } from './useFinancialOperations';

/**
 * useFinanceContext
 * Hook especializado en consolidar las operaciones financieras cruzadas y construir
 * los objetos masivos memorizados `financeData` y `financeActions`.
 */
export function useFinanceContext(props = {}) {
  const financialOps = useFinancialOperations({
    accounts: props.accounts, setAccounts: props.setAccounts,
    transactions: props.transactions, setTransactions: props.setTransactions,
    debtsAndLoans: props.debtsAndLoans, setDebtsAndLoans: props.setDebtsAndLoans,
    investments: props.investments, setInvestments: props.setInvestments,
    categories: props.categories, setCategories: props.setCategories,
    trm: props.trm, userProfile: props.userProfile, isResettingRef: props.isResettingRef,
    baseAddTransaction: props.baseAddTransaction, baseSaveTransaction: props.baseSaveTransaction,
    baseUpdateTransaction: props.baseUpdateTransaction, baseDeleteTransaction: props.baseDeleteTransaction,
    baseExecuteTransfer: props.baseExecuteTransfer, baseAddPayment: props.baseAddPayment,
    baseDeletePayment: props.baseDeletePayment, baseAddDisbursement: props.baseAddDisbursement,
    baseAddInvestment: props.baseAddInvestment, baseDeleteInvestment: props.baseDeleteInvestment,
    baseAddDebtOrLoan: props.baseAddDebtOrLoan, baseSaveLoan: props.baseSaveLoan,
    baseDeleteDebtOrLoan: props.baseDeleteDebtOrLoan
  });

  const financeData = useMemo(() => ({
    accounts: props.accounts || [],
    transactions: props.transactions || [],
    monthlyTransactions: props.monthlyTransactions || [],
    scopedTransactions: props.scopedTransactions || [],
    categories: props.categories || [],
    investments: props.investments || [],
    debtsAndLoans: props.debtsAndLoans || [],
    recurringPayments: props.recurringPayments || [],
    subscriptions: props.subscriptions || [],
    budgets: props.budgets || {},
    savingsGoals: props.savingsGoals || [],
    monthlyStats: props.monthlyStats || {},
    netWorth: props.netWorth || 0,
    taxMetrics: props.taxMetrics || {},
    trm: props.trm || 4000,
    userProfile: props.userProfile || {},
    selectedDate: props.selectedDate,
    selectedMonth: props.selectedMonth,
    selectedYear: props.selectedYear,
    selectedDay: props.selectedDay,
    currentMonthLabel: props.currentMonthLabel,
    widgets: props.widgets,
    tomorrowDebtAlerts: props.tomorrowDebtAlerts || [],
    user: props.user || null,
    theme: props.theme || 'dark',
    securitySettings: props.securitySettings || {},
    isLocked: props.isLocked || false,
    failedAttempts: props.failedAttempts || 0,
    showTutorial: props.showTutorial || false,
    syncStatus: props.syncStatus || 'idle',
    syncUser: props.syncUser || null,
    isCloudEnabled: props.isCloudEnabled || false,
    livePrices: props.livePrices || {}
  }), [
    props.accounts, props.transactions, props.monthlyTransactions, props.scopedTransactions,
    props.categories, props.investments, props.debtsAndLoans, props.recurringPayments,
    props.subscriptions, props.budgets, props.savingsGoals, props.monthlyStats,
    props.netWorth, props.taxMetrics, props.trm, props.userProfile, props.selectedDate,
    props.selectedMonth, props.selectedYear, props.selectedDay, props.currentMonthLabel,
    props.widgets, props.tomorrowDebtAlerts, props.user, props.theme, props.securitySettings,
    props.isLocked, props.failedAttempts, props.showTutorial, props.syncStatus, props.syncUser,
    props.isCloudEnabled, props.livePrices
  ]);

  const financeActions = useMemo(() => ({
    ...financialOps,
    ...props.modalControls,
    handleTabChange: props.handleTabChange,
    handleResetTab: props.handleResetTab,
    setSelectedDate: props.setSelectedDate,
    setSelectedDay: props.setSelectedDay,
    setWidgets: props.setWidgets,
    setBudgets: props.setBudgets,
    setSubscriptions: props.setSubscriptions,
    setSecuritySettings: props.setSecuritySettings,
    setTheme: props.setTheme,
    setShowTutorial: props.setShowTutorial,
    showMonthPicker: props.showMonthPicker,
    setShowMonthPicker: props.setShowMonthPicker,
    isEditWidgetsModalOpen: props.isEditWidgetsModalOpen,
    setIsEditWidgetsModalOpen: props.setIsEditWidgetsModalOpen,
    handleUnlock: props.handleUnlock,
    handleVerifyPin: props.handleVerifyPin,
    handleUpdatePin: props.handleUpdatePin,
    handleReviewDebtAlert: props.handleReviewDebtAlert,
    handleDismissAlert: props.handleDismissAlert,
    formatMoney: props.formatMoney,
    handleGoBackFromSubView: props.handleGoBackFromSubView,
    fromSettings: props.fromSettings,
    setFromSettings: props.setFromSettings,
    handleAddCategory: props.handleAddCategory,
    handleUpdateCategory: props.handleUpdateCategory,
    handleDeleteCategory: props.handleDeleteCategory,
    handleAddSubcategory: props.handleAddSubcategory,
    handleUpdateSubcategory: props.handleUpdateSubcategory,
    handleDeleteSubcategory: props.handleDeleteSubcategory,
    handleAddAccount: props.handleAddAccount,
    handleUpdateAccount: props.handleUpdateAccount,
    handleDeleteAccount: props.handleDeleteAccount,
    handleReorderAccounts: props.handleReorderAccounts,
    updateAccountsOrder: props.updateAccountsOrder,
    fetchAccounts: props.fetchAccounts,
    handleUpdateDebtOrLoan: props.handleUpdateDebtOrLoan,
    handleUpdateInvestment: props.baseUpdateInvestment,
    handleAddRecurring: props.handleAddRecurring,
    handleUpdateRecurring: props.handleUpdateRecurring,
    handleDeleteRecurring: props.handleDeleteRecurring,
    handleToggleActiveRecurring: props.handleToggleActiveRecurring,
    handleAddGoal: props.handleAddGoal,
    handleUpdateGoal: props.handleUpdateGoal,
    handleDeleteGoal: props.handleDeleteGoal,
    handlePrevMonth: props.handlePrevMonth,
    handleNextMonth: props.handleNextMonth,
    handleResetToToday: props.handleResetToToday,
    handleChangeMonth: props.handleChangeMonth,
    handleRestoreBackup: props.handleRestoreBackup,
    handleResetData: props.handleResetData,
    handleUpdateProfile: props.handleUpdateProfile,
    pushLocalToCloud: props.pushLocalToCloud,
    pullCloudToLocal: props.pullCloudToLocal,
    onLogout: props.handleGlobalLogout
  }), [
    financialOps, props.modalControls, props.handleTabChange, props.handleResetTab,
    props.setSelectedDate, props.setSelectedDay, props.setWidgets, props.setBudgets,
    props.setSubscriptions, props.setSecuritySettings, props.setTheme, props.setShowTutorial,
    props.showMonthPicker, props.setShowMonthPicker, props.isEditWidgetsModalOpen,
    props.setIsEditWidgetsModalOpen, props.handleUnlock, props.handleVerifyPin,
    props.handleUpdatePin, props.handleReviewDebtAlert, props.handleDismissAlert,
    props.formatMoney, props.handleGoBackFromSubView, props.fromSettings, props.setFromSettings,
    props.handleAddCategory, props.handleUpdateCategory, props.handleDeleteCategory,
    props.handleAddSubcategory, props.handleUpdateSubcategory, props.handleDeleteSubcategory,
    props.handleAddAccount, props.handleUpdateAccount, props.handleDeleteAccount,
    props.handleReorderAccounts, props.updateAccountsOrder, props.fetchAccounts,
    props.handleUpdateDebtOrLoan, props.baseUpdateInvestment, props.handleAddRecurring,
    props.handleUpdateRecurring, props.handleDeleteRecurring, props.handleToggleActiveRecurring,
    props.handleAddGoal, props.handleUpdateGoal, props.handleDeleteGoal, props.handlePrevMonth,
    props.handleNextMonth, props.handleResetToToday, props.handleChangeMonth,
    props.handleRestoreBackup, props.handleResetData, props.handleUpdateProfile,
    props.pushLocalToCloud, props.pullCloudToLocal, props.handleGlobalLogout
  ]);

  return { financeData, financeActions, financialOps };
}

export default useFinanceContext;
